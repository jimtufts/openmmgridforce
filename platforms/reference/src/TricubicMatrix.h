inline void tricubicAssemble(const double X[64], double a[64]) {
    for (int i = 0; i < 64; i++) {
        double s = 0.0;
        for (int j = 0; j < 64; j++)
            s += TRICUBIC_COEFFICIENTS[i][j] * X[j];
        a[i] = s;
    }
}

// Value + gradient w.r.t. fractional cell coords (fx,fy,fz in [0,1]).
inline void tricubicEvalVG(const double a[64], double fx, double fy, double fz,
                           double* value, double* gx, double* gy, double* gz) {
    double px[4], py[4], pz[4], dpx[4], dpy[4], dpz[4];
    px[0]=1.0; px[1]=fx; px[2]=fx*fx; px[3]=fx*fx*fx;
    py[0]=1.0; py[1]=fy; py[2]=fy*fy; py[3]=fy*fy*fy;
    pz[0]=1.0; pz[1]=fz; pz[2]=fz*fz; pz[3]=fz*fz*fz;
    dpx[0]=0.0; dpx[1]=1.0; dpx[2]=2.0*fx; dpx[3]=3.0*fx*fx;
    dpy[0]=0.0; dpy[1]=1.0; dpy[2]=2.0*fy; dpy[3]=3.0*fy*fy;
    dpz[0]=0.0; dpz[1]=1.0; dpz[2]=2.0*fz; dpz[3]=3.0*fz*fz;
    double v=0.0, vx=0.0, vy=0.0, vz=0.0;
    for (int k = 0; k < 4; k++)
        for (int j = 0; j < 4; j++)
            for (int i = 0; i < 4; i++) {
                double c = a[i + 4*j + 16*k];
                v  += c * px[i]  * py[j]  * pz[k];
                vx += c * dpx[i] * py[j]  * pz[k];
                vy += c * px[i]  * dpy[j] * pz[k];
                vz += c * px[i]  * py[j]  * dpz[k];
            }
    *value=v; *gx=vx; *gy=vy; *gz=vz;
}

